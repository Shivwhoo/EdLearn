import { jsPDF } from 'jspdf';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const doc = new jsPDF({
  orientation: 'portrait',
  unit: 'mm',
  format: 'a4',
});

const PW = 210;
const PH = 297;
const MARGIN = 18;
const CONTENT_W = PW - MARGIN * 2;
let y = 20;

function checkPageBreak(neededHeight) {
  if (y + neededHeight > PH - 18) {
    doc.addPage();
    y = 22;
    addPageChrome();
  }
}

function addPageChrome() {
  // Header bar
  doc.setFillColor(15, 23, 42); // slate-900
  doc.rect(0, 0, PW, 13, 'F');

  doc.setFillColor(37, 99, 235); // blue-600
  doc.rect(0, 0, 4, 13, 'F');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(255, 255, 255);
  doc.text('EdLearn', 8, 9);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(148, 163, 184); // slate-400
  doc.text('Architecture Audit, Platform Upgrades & Gaps Report', 30, 9);

  // Footer bar
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7.5);
  doc.setTextColor(148, 163, 184);
  doc.text(`Page ${doc.internal.getNumberOfPages()}`, PW - MARGIN - 8, PH - 8);
  doc.text('Confidential — Generated by EdLearn Lead Software Architecture Team', MARGIN, PH - 8);
}

// ─── Cover Header ─────────────────────────────────────────────────────────────
addPageChrome();

y = 24;
doc.setFont('helvetica', 'bold');
doc.setFontSize(20);
doc.setTextColor(15, 23, 42);
doc.text('EdLearn Platform Engineering Report', MARGIN, y);

y += 7;
doc.setFont('helvetica', 'bold');
doc.setFontSize(11);
doc.setTextColor(37, 99, 235);

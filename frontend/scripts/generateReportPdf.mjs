y += 5.5;
doc.setFont('helvetica', 'normal');
doc.setFontSize(8);
doc.setTextColor(100, 116, 139);
doc.text(`Date: ${new Date().toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric' })}  |  Status: Production-Grade (84/84 Tests Passed, 0 Typecheck Errors)`, MARGIN, y);

y += 3.5;
doc.setDrawColor(226, 232, 240);
doc.setLineWidth(0.4);
doc.line(MARGIN, y, PW - MARGIN, y);
y += 6;

function addSectionHeader(title, color = [15, 23, 42]) {
  checkPageBreak(12);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11.5);
  doc.setTextColor(color[0], color[1], color[2]);
  doc.text(title, MARGIN, y);
  y += 2.5;
  doc.setDrawColor(color[0], color[1], color[2]);
  doc.setLineWidth(0.3);
  doc.line(MARGIN, y, MARGIN + 35, y);
  y += 4.5;
}

function addSubsectionHeader(title) {
  checkPageBreak(8);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9.5);
  doc.setTextColor(30, 41, 59);
  doc.text(title, MARGIN, y);
  y += 4;
}

function addParagraph(text) {
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(51, 65, 85);
  const lines = doc.splitTextToSize(text, CONTENT_W);
  checkPageBreak(lines.length * 3.7 + 2);
  doc.text(lines, MARGIN, y);
  y += lines.length * 3.7 + 2.5;
}

function addBullet(label, description) {
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(15, 23, 42);
  
  const fullText = `• ${label}: ${description}`;
  const lines = doc.splitTextToSize(fullText, CONTENT_W);
  checkPageBreak(lines.length * 3.7 + 1.5);
  
  doc.text(lines, MARGIN, y);
  y += lines.length * 3.7 + 1.5;
}

